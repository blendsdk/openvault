/** Input for the pure Compose and manifest renderers. */
export interface ComposeScaffoldInput {
  /** OpenVault project name. */
  readonly project: string;
  /** Compose-safe service slug. */
  readonly service: string;
  /** Secret names granted to the identity. */
  readonly entries: readonly string[];
}

const AGENT_IMAGE = "blendsdk/openvault-agent:1.1.0";
const COMPOSE_PROJECT_VAR = "$" + "{COMPOSE_PROJECT_NAME}";
const JOIN_TOKEN_VAR = "$" + "{OPENVAULT_JOIN_TOKEN}";

/** Emits a JSON string, which is also a valid YAML double-quoted scalar. */
function quote(value: string): string {
  return JSON.stringify(value);
}

/** Returns the per-Compose-project manifest file name template. */
export function manifestFileName(project: string, service: string): string {
  return `openvault.${COMPOSE_PROJECT_VAR}.${project}.${service}.manifest.yaml`;
}

/**
 * Renders the hardened per-service Compose snippet.
 *
 * Every interpolated key and scalar is quoted so a leading-digit or
 * boolean-like name cannot change the YAML type. The join token appears only as
 * a `${OPENVAULT_JOIN_TOKEN}` placeholder.
 *
 * @param input - Project, service, and entry names.
 * @returns A deterministic YAML document.
 */
export function renderCompose(input: ComposeScaffoldInput): string {
  const agent = `openvault-agent-${input.service}`;
  // Include the OpenVault project in every host path. Two tenants can reuse a
  // Compose project and service name; they must never share a tmpfs directory
  // or a state directory.
  const outputPath = `/dev/shm/openvault/${input.project}/${COMPOSE_PROJECT_VAR}/${input.service}`;
  const statePath = `./openvault-state/${input.project}/${COMPOSE_PROJECT_VAR}/${input.service}`;
  const manifestPath = `./${manifestFileName(input.project, input.service)}`;
  return `# Generated by OpenVault. Merge the application keys into your service.
# Before first start, create the agent-owned directories:
# install -d -m 0700 -o 10001 -g 10001 "${outputPath}" "${statePath}"
# install -m 0444 -o 10001 -g 10001 ./openvault-ca.pem "${manifestPath}"
# Set OPENVAULT_JOIN_TOKEN in your shell or an env file outside this Compose file.
# Never commit the token to the Compose file or to source control.
${quote("services")}:
  ${quote(agent)}:
    ${quote("image")}: ${quote(AGENT_IMAGE)}
    ${quote("command")}: [${quote("run")}]
    ${quote("user")}: ${quote("10001:10001")}
    ${quote("read_only")}: true
    ${quote("cap_drop")}: [ALL]
    ${quote("security_opt")}: ["no-new-privileges:true"]
    ${quote("environment")}:
      ${quote("OPENVAULT_URL")}: ${quote("https://openvaultd:8444")}
      ${quote("OPENVAULT_CA_FILE")}: ${quote("/etc/openvault/ca.pem")}
      ${quote("OPENVAULT_JOIN_TOKEN")}: ${quote(JOIN_TOKEN_VAR)}
      ${quote("OPENVAULT_PROJECT")}: ${quote(input.project)}
      ${quote("OPENVAULT_SERVICE")}: ${quote(input.service)}
      ${quote("COMPOSE_PROJECT_NAME")}: ${quote(COMPOSE_PROJECT_VAR)}
      ${quote("OPENVAULT_MANIFEST")}: ${quote("/etc/openvault/manifest.yaml")}
      ${quote("OPENVAULT_OUTPUT_DIR")}: ${quote("/run/secrets")}
      ${quote("OPENVAULT_STATE_DIR")}: ${quote("/var/lib/openvault")}
    ${quote("tmpfs")}:
      - /run/openvault:uid=10001,gid=10001,mode=0700,size=16m
    ${quote("volumes")}:
      - ${quote("type")}: ${quote("bind")}
        ${quote("source")}: ${outputPath}
        ${quote("target")}: ${quote("/run/secrets")}
        ${quote("bind")}:
          ${quote("create_host_path")}: false
      - ${quote("type")}: ${quote("bind")}
        ${quote("source")}: ${statePath}
        ${quote("target")}: ${quote("/var/lib/openvault")}
        ${quote("bind")}:
          ${quote("create_host_path")}: false
      - ${quote("type")}: ${quote("bind")}
        ${quote("source")}: ${quote("./openvault-ca.pem")}
        ${quote("target")}: ${quote("/etc/openvault/ca.pem")}
        ${quote("read_only")}: true
      - ${quote("type")}: ${quote("bind")}
        ${quote("source")}: ${manifestPath}
        ${quote("target")}: ${quote("/etc/openvault/manifest.yaml")}
        ${quote("read_only")}: true
    ${quote("networks")}: [default, vault_net]
    ${quote("healthcheck")}:
      ${quote("test")}: ["CMD", "ov-agent", "health", "--ready"]
      ${quote("interval")}: 10s
      ${quote("timeout")}: 10s
      ${quote("retries")}: 3
      ${quote("start_period")}: 10s
  ${quote(input.service)}:
    # Merge these keys into the application service.
    ${quote("user")}: ${quote("10001:10001")}
    ${quote("volumes")}:
      - ${quote("type")}: ${quote("bind")}
        ${quote("source")}: ${outputPath}
        ${quote("target")}: ${quote("/run/secrets")}
        ${quote("read_only")}: true
        ${quote("bind")}:
          ${quote("create_host_path")}: false
    ${quote("depends_on")}:
      ${quote(agent)}:
        ${quote("condition")}: ${quote("service_healthy")}
${quote("networks")}:
  ${quote("vault_net")}:
    ${quote("external")}: true
`;
}

/**
 * Renders a manifest skeleton for the scaffold entries.
 *
 * The operator may add modes, optional flags, or env targets after review.
 *
 * @param input - Project, service, and entry names.
 * @returns A deterministic YAML document.
 */
export function renderManifest(input: ComposeScaffoldInput): string {
  if (input.entries.length === 0) {
    return `# Add at least one entry before starting the agent.
${quote("project")}: ${quote(input.project)}
${quote("service")}: ${quote(input.service)}
${quote("refresh")}: ${quote("300s")}
${quote("output_dir")}: ${quote("/run/secrets")}
${quote("entries")}: []
`;
  }
  const entries = input.entries
    .map(
      (name) => `  - ${quote("name")}: ${quote(name)}
    ${quote("file")}: ${quote(name)}`,
    )
    .join("\n");
  return `${quote("project")}: ${quote(input.project)}
${quote("service")}: ${quote(input.service)}
${quote("refresh")}: ${quote("300s")}
${quote("output_dir")}: ${quote("/run/secrets")}
${quote("entries")}:
${entries}
`;
}
