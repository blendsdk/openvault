#!/usr/bin/env node

import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  CTypeGenerator,
  PostgreSQLIntrospector,
  SchemaContainer,
  TypeGenerator,
} from "blendsdk/codegen";
import { PostgreSQLDatabase } from "blendsdk/postgresql";

const databaseUrl = process.env.OPENVAULT_DB_URL;
if (!databaseUrl) {
  throw new Error("OPENVAULT_DB_URL is required to generate database types.");
}

const parsed = new URL(databaseUrl);
const db = new PostgreSQLDatabase({
  host: parsed.hostname.replace(/^\[|\]$/g, ""),
  port: parsed.port ? Number(parsed.port) : 5432,
  database: decodeURIComponent(parsed.pathname.replace(/^\//, "")),
  user: decodeURIComponent(parsed.username),
  pass: decodeURIComponent(parsed.password),
});

const generatedHeader = "// Generated by scripts/generate-db-types.mjs. Do not edit by hand.\n\n";

try {
  const schema = new SchemaContainer();
  const introspector = new PostgreSQLIntrospector(db);
  await introspector.introspect(schema);

  // The migration ledger is infrastructure, not a domain table. Keep it out of generated
  // row types and CType constants.
  const domainSchema = {
    getAll: () => schema.getAll().filter((object) => object.getName() !== "blendsdk_migrations"),
  };
  const types = await new TypeGenerator().generate(domainSchema);
  const constantTypes = await introspector.introspectConstantTypes();
  delete constantTypes.blendsdk_migrations;
  delete constantTypes["public.blendsdk_migrations"];
  const constants = await new CTypeGenerator().generate(constantTypes);

  const outputDirectory = join(import.meta.dirname, "..", "src", "database");
  await writeFile(
    join(outputDirectory, "generated-types.ts"),
    `${generatedHeader}${types}\n`,
    "utf8",
  );
  await writeFile(join(outputDirectory, "ctypes.ts"), `${generatedHeader}${constants}\n`, "utf8");
  process.stdout.write("Generated database types and CType constants.\n");
} finally {
  await db.disconnect();
}
