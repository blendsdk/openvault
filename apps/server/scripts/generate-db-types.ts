import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  CTypeGenerator,
  PostgreSQLIntrospector,
  SchemaContainer,
  TypeGenerator,
} from "blendsdk/codegen";
import { PostgreSQLDatabase } from "blendsdk/postgresql";
import { parseDatabaseUrl } from "../src/db/url.js";

const databaseUrl = process.env.OPENVAULT_DB_URL;
if (!databaseUrl) {
  throw new Error("OPENVAULT_DB_URL is required to generate database types.");
}

const db = new PostgreSQLDatabase(parseDatabaseUrl(databaseUrl));
const generatedHeader = "// Generated by scripts/generate-db-types.ts. Do not edit by hand.\n\n";

/**
 * Schema container that hides infrastructure tables from the generators.
 *
 * The migration ledger is owned by BlendSDK, not by the OpenVault domain model. Filtering it
 * here keeps generated row types and constants focused on product tables.
 */
class DomainSchemaContainer extends SchemaContainer {
  public constructor(private readonly source: SchemaContainer) {
    super();
  }

  public override getAll() {
    return this.source.getAll().filter((object) => object.getName() !== "blendsdk_migrations");
  }
}

try {
  const schema = new SchemaContainer();
  const introspector = new PostgreSQLIntrospector(db);
  await introspector.introspect(schema);

  const types = await new TypeGenerator().generate(new DomainSchemaContainer(schema));
  const constantTypes = await introspector.introspectConstantTypes();
  delete constantTypes.blendsdk_migrations;
  delete constantTypes["public.blendsdk_migrations"];
  const constants = await new CTypeGenerator().generate(constantTypes);

  const outputDirectory = join(import.meta.dirname, "..", "src", "database");
  await writeFile(
    join(outputDirectory, "generated-types.ts"),
    `${generatedHeader}${types}\n`,
    "utf8",
  );
  await writeFile(join(outputDirectory, "ctypes.ts"), `${generatedHeader}${constants}\n`, "utf8");
  process.stdout.write("Generated database types and CType constants.\n");
} finally {
  await db.disconnect();
}
